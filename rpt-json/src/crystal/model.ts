/** Reads prompts from CRMetaObjects XML documents with a small tag scanner (no XML library). */
export function parsePrompts(documents: string[]): PromptInfo[] {
  const prompts: PromptInfo[] = [];
  const tag = (xml: string, name: string) => new RegExp(`<${name}>([^<]*)</${name}>`).exec(xml)?.[1];
  const decode = (text: string) => text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');
  for (const doc of documents) {
    for (const group of doc.split(/<MetaObject\b/).slice(1)) {
      const groupName = decode(tag(group, 'Name') ?? '');
      for (const prompt of group.split(/<Prompt\b/).slice(1)) {
        prompts.push({
          group: groupName,
          prompt: decode(tag(prompt, 'Desc') ?? ''),
          valueType: tag(prompt, 'ValueType'),
          allowRange: tag(prompt, 'AllowRangeValue') === 'true',
          allowDiscrete: tag(prompt, 'AllowDiscreteValue') !== 'false',
          allowMultiple: tag(prompt, 'AllowMultiValues') === 'true',
          nullable: tag(prompt, 'Nullable') === 'true',
        });
      }
    }
  }
  return prompts;
}

/** Adds prompt options to parameters, matched by prompt text or by the prompt group's name. */
export function applyPrompts(parameters: ParameterInfo[], prompts: PromptInfo[]): void {
  for (const parameter of parameters) {
    const prompt = prompts.find((p) => (parameter.prompt && p.prompt === parameter.prompt) || p.group.endsWith(` for ${parameter.name}`) || p.group === parameter.name);
    if (!prompt) continue;
    parameter.allowRange = prompt.allowRange;
    parameter.allowDiscrete = prompt.allowDiscrete;
    parameter.allowMultiple = prompt.allowMultiple;
    parameter.nullable = prompt.nullable;
  }
}

